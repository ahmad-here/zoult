import core from './articles/core.js'
import seo from './articles/seo.js'
import money from './articles/money.js'
import tech from './articles/tech.js'
import webdev from './articles/webdev.js'
import social from './articles/social.js'
import shop from './articles/shop.js'
import growth from './articles/growth.js'
import finance from './articles/finance.js'
import { asset } from '@/lib/site'

export interface Blog {
  id: number
  slug: string
  title: string
  category: string
  description: string
  date: string
  image: number
  content: string
}

/** All articles, newest first. */
export const blogs: Blog[] = [...core, ...seo, ...money, ...tech, ...webdev, ...social, ...shop, ...growth, ...finance].sort((a, b) =>
  b.date.localeCompare(a.date)
)

export const getBlog = (slug: string) => blogs.find((b) => b.slug === slug)

/** Unique cover per article, generated by scripts/generate-covers.mjs. */
export const blogImagePath = (blog: Pick<Blog, 'slug'>) => `/images/blog/${blog.slug}.webp`
export const blogImage = (blog: Pick<Blog, 'slug'>) => asset(blogImagePath(blog))

export const readingTime = (content: string) => Math.max(1, Math.round(content.split(/\s+/).length / 220))

export const formatDate = (date: string) =>
  new Date(date + 'T00:00:00Z').toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    timeZone: 'UTC',
  })

/** Related posts: same category first, then most recent. */
export const relatedBlogs = (blog: Blog, count = 3) =>
  [
    ...blogs.filter((b) => b.slug !== blog.slug && b.category === blog.category),
    ...blogs.filter((b) => b.slug !== blog.slug && b.category !== blog.category),
  ].slice(0, count)

export const categories = Array.from(new Set(blogs.map((b) => b.category)))
